def bars(rows, maxv, unit="", cls=""):
    out = ['<div class="bars %s">' % cls]
    for label, val, note in rows:
        w = max(3, round(val / maxv * 100))
        out.append('<div class="brow"><span class="bl">%s</span><span class="bt"><i style="width:%d%%"></i></span><span class="bv">%s%s</span><span class="bn">%s</span></div>' % (label, w, val, unit, note))
    out.append('</div>')
    return "".join(out)

